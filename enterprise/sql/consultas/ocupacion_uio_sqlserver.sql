-- Consulta fija de solo lectura, basada en la consulta UIO proporcionada por el usuario.
-- La precedencia del WHERE se conserva; no se añade ningún filtro silencioso.
SELECT TOP (50001)
 P.POSICION_ID,P.POSICION_COD,tbx2.BODEGA,
 REPLACE(REVERSE(PARSENAME(REPLACE(REVERSE(REPLACE(tbx2.POSICION_CO,'.','||')),'-','.'),1)),'||','.') AS CALLE,
 REPLACE(REVERSE(PARSENAME(REPLACE(REVERSE(REPLACE(tbx2.POSICION_CO,'.','||')),'-','.'),2)),'||','.') AS COLUMNA,
 REPLACE(REVERSE(PARSENAME(REPLACE(REVERSE(REPLACE(tbx2.POSICION_CO,'.','||')),'-','.'),3)),'||','.') AS NIVEL,
 REPLACE(REVERSE(PARSENAME(REPLACE(REVERSE(REPLACE(tbx2.POSICION_CO,'.','||')),'-','.'),4)),'||','.') AS PROFUNDIDAD,
 tbx1.cliente_id AS COD_CLIENTE,
 CASE WHEN tbx1.estado_posicion='OCUPADA' THEN 'OCUPADA' ELSE 'DISPONIBLE' END AS STATUS_OCUPACION,
 CASE WHEN P.LARGO=120 AND P.ALTO=135 AND P.ANCHO=100 AND P.PESO=1000 THEN 'RACK'
 WHEN P.LARGO=60 AND P.ALTO=60 AND P.ANCHO=240 AND P.PESO=500 THEN 'RACK_LIVIANO'
 WHEN P.LARGO=40 AND P.ALTO=35 AND P.ANCHO=100 AND P.PESO=100 THEN 'ESTANTERIA'
 WHEN P.LARGO=60 AND P.ALTO=26 AND P.ANCHO=29 AND P.PESO=8 THEN 'GAVETA'
 WHEN P.LARGO=300 AND P.ALTO=300 AND P.ANCHO=300 AND P.PESO=2000 THEN 'PISO'
 ELSE 'SIN_ASIGNAR_TIPO' END AS TIPO_POS,
 CASE WHEN P.POSICION_COD LIKE 'BF%' THEN 'CD_FARMA' WHEN P.POSICION_COD LIKE 'B2%' THEN 'CD_QUITO2'
 WHEN P.POSICION_COD LIKE 'B4%' THEN 'CD_QUITO4' ELSE 'CD_QUITO1' END AS ALMACEN,
 'QUITO' AS CIUDAD,P.POS_LOCKEADA,P.ORDEN_PICKING,P.ORDEN_LOCATOR,
 P.LARGO,P.ANCHO,P.ALTO,P.VOLUMEN,P.PESO,P.PICKING,P.ABASTECIBLE,P.BESTFIT,P.BESTFIT_PERMITE_ABAST,P.PCJ_OCUPACION
FROM POSICION P
 LEFT JOIN (SELECT posicion_id,cliente_id,estado_posicion FROM view_web_estado_posicion WHERE estado_posicion='OCUPADA') tbx1 ON tbx1.posicion_id=P.POSICION_ID
 LEFT JOIN (SELECT POSICION_COD,
  CASE WHEN CHARINDEX('-',POSICION_COD)>0 THEN LEFT(POSICION_COD,CHARINDEX('-',POSICION_COD)-1) ELSE POSICION_COD END BODEGA,
  CASE WHEN CHARINDEX('-',POSICION_COD)>0 THEN SUBSTRING(POSICION_COD,CHARINDEX('-',POSICION_COD)+1,50) ELSE '' END POSICION_CO
 FROM POSICION) tbx2 ON tbx2.POSICION_COD=P.POSICION_COD
WHERE (P.POS_VACIA=0 AND P.POSICION_COD NOT LIKE '%PRUEBA%') OR (P.ALTO<>0 AND P.ANCHO<>0 AND P.LARGO<>0)
ORDER BY P.POSICION_COD,tbx1.cliente_id;
